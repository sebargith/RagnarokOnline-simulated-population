"""Frozen (R2, 2026-11-03): off the main path; OpenKore auto (scripts/run_r1.py) replaces it.
Kept for its tests and evidence; do not extend.

Build config/walk-zones.json from OpenKore's pinned portals table and field files.

Portals are read as OpenKore's FileParsers::parsePortals reads them and kept with the
filter of M1Travel::walk_graph (free, talk-less, no dynamic group), but same-map walk
portals are kept too. Each portal gets the zone (agent/walk.py) of the walkable cell
used to enter it and of the cell it lands on; portals whose either end has no walkable
cell within APPROACH, or whose map has no field file, are left out. Anchors are those
cells per map, so any cell's zone is found by walking from it to the first anchor.
"""
import argparse
import json
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from agent import walk  # noqa: E402

OPENKORE = ROOT.parent/'vendor/openkore'
PORTALS = 'tables/portals.txt'
LINE = re.compile(r'^([\w|@|-]+)\s(\d{1,3})\s(\d{1,3})\s([\w|@|-]+)\s(\d{1,3})\s(\d{1,3})\s?(.*)')
GROUP = re.compile(r'(?:^|\s)\[(\^?)([A-Za-z0-9_]+)\](?=\s|$)')


def portals(text):
    """Free, talk-less, permanent portals: (map, x, y, to, tx, ty), deduplicated and sorted."""
    out = set()
    for line in text.splitlines():
        if line.startswith('#'):
            continue
        line = re.sub(r'\s+', ' ', line.replace('\r', '').replace('\n', '')).strip()
        line = re.sub(r'(.*)[\s\t]+#.*$', r'\1', line)
        match = LINE.match(line)
        if not match:
            continue
        *ends, misc = match.groups()
        misc, groups = GROUP.subn(' ', misc)
        if groups or misc.strip():
            continue  # Dynamic group, cost, ticket or talk sequence.
        m, x, y, to, tx, ty = ends
        out.add((m, int(x), int(y), to, int(tx), int(ty)))
    return sorted(out)


def build(fields=None):
    rows = portals((OPENKORE/PORTALS).read_text(encoding='utf-8', errors='replace'))
    ends = {}  # map -> {(x, y): walkable anchor cell}
    for m, x, y, to, tx, ty in rows:
        ends.setdefault(m, {})[(x, y)] = None
        ends.setdefault(to, {})[(tx, ty)] = None
    zone = {}  # (map, anchor) -> zone id, numbered per map by sorted anchor
    for name in sorted(ends):
        g = walk.grid.__wrapped__(name, fields)
        for cell in ends[name]:
            ends[name][cell] = g and walk.approach(g, *cell)
        todo, label = sorted({a for a in ends[name].values() if a}), 0
        for anchor in todo:
            if (name, anchor) in zone:
                continue
            label += 1
            reached = walk.flood(g, anchor)
            for other in todo:
                if other in reached:
                    zone[(name, other)] = label
    out, anchors = [], {}
    for m, x, y, to, tx, ty in rows:
        a, b = ends[m][(x, y)], ends[to][(tx, ty)]
        if a and b:
            out.append([m, x, y, to, tx, ty, zone[(m, a)], zone[(to, b)]])
            for name, cell in ((m, a), (to, b)):
                anchors.setdefault(name, set()).add((*cell, zone[(name, cell)]))
    commit = subprocess.run(['git', '-C', str(OPENKORE), 'rev-parse', 'HEAD'],
                            capture_output=True, text=True, check=True).stdout.strip()
    return {'version': 1, 'source': {'openkore_commit': commit, 'portals': PORTALS, 'fields': 'fields/*.fld2.gz'},
            'note': 'Generated by scripts/build_walk_zones.py; do not edit by hand.',
            'connectivity': '4-neighbour walkable cells; portals entered from the nearest walkable cell within 2',
            'portals': out, 'anchors': {m: sorted(map(list, c)) for m, c in sorted(anchors.items())}}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', default=str(walk.ZONES))
    args = parser.parse_args()
    doc = build()
    Path(args.out).write_text(json.dumps(doc, separators=(',', ':')) + '\n', encoding='utf-8')
    print(f"{len(doc['portals'])} portals, {len(doc['anchors'])} maps -> {args.out}")


if __name__ == '__main__':
    main()
