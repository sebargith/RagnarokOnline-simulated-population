"""Build config/p5-loot.json: what each hunted monster drops and what the loot is worth.

Monsters are the ones in config/p5-monsters.json (fields the agents may hunt).
Drops and items come from the pinned rAthena pre-Renewal mob_db.yml and
item_db_*.yml: rate in 1/10000 (official 1x rates; battle_config multipliers are
not applied), NPC sell price as rAthena derives it, weight in game units.
Card and MVP drops are kept and flagged: the economy design treats them as rare.
Only the fixed indentation layout of the YAML files is parsed (no PyYAML).
"""
import argparse
import json
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT/'scripts'))
from build_p5_equipment import RATHENA, prices  # noqa: E402

MOB_DB = 'db/pre-re/mob_db.yml'
ITEM_DBS = ('db/pre-re/item_db_equip.yml', 'db/pre-re/item_db_etc.yml', 'db/pre-re/item_db_usable.yml')
RARE_RATE = 10  # 0.1 %: below this, a drop is not something a small community can plan on


def items(text):
    """AegisName -> {Id, Name, Type, Buy, Sell, Weight} (top-level scalar keys only)."""
    out, item = {}, None
    for line in text.splitlines():
        if line.startswith('  - Id: '):
            item = {'Id': int(line[8:])}
        elif item is not None and line.startswith('    ') and not line.startswith('     '):
            key, _, value = line.strip().partition(':')
            if value.strip():
                item[key] = value.strip()
                if key == 'AegisName':
                    out[value.strip()] = item
    return out


def drops(text):
    """Mob id -> {name, drops: [{item, rate, steal_protected?}], mvp_drops: [...]}"""
    out, mob, section, drop = {}, None, None, None
    for line in text.splitlines():
        if line.startswith('  - Id: '):
            mob = out.setdefault(int(line[8:]), {'drops': [], 'mvp_drops': []})
            section = None
        elif mob is None or not line.strip() or line.lstrip().startswith('#'):
            continue
        elif line.startswith('    ') and not line.startswith('     '):
            key, _, value = line.strip().partition(':')
            section = {'Drops': 'drops', 'MvpDrops': 'mvp_drops'}.get(key)
            if key == 'Name':
                mob['name'] = value.strip()
        elif section and line.startswith('      - Item: '):
            drop = {'item': line.split(': ', 1)[1].strip()}
            mob[section].append(drop)
        elif section and line.startswith('        ') and drop is not None:
            key, _, value = line.strip().partition(': ')
            if key == 'Rate':
                drop['rate'] = int(value)
            elif key == 'StealProtected':
                drop['steal_protected'] = value == 'true'
    return out


def commit(path):
    return subprocess.run(['git', '-C', str(path), 'rev-parse', 'HEAD'],
                          capture_output=True, text=True, check=True).stdout.strip()


def build(monsters_path=ROOT/'config/p5-monsters.json'):
    hunted = json.loads(Path(monsters_path).read_text(encoding='utf-8'))['monsters']
    db = {}
    for name in ITEM_DBS:
        db.update(items((RATHENA/name).read_text(encoding='utf-8')))
    mobs = drops((RATHENA/MOB_DB).read_text(encoding='utf-8'))
    monsters, used = {}, {}
    for mid in sorted(hunted, key=int):
        rows = []
        for kind in ('drops', 'mvp_drops'):
            for d in mobs[int(mid)][kind]:
                item = db.get(d['item'])
                if item is None:
                    raise ValueError(f'mob {mid}: unknown item {d["item"]}')
                used[str(item['Id'])] = item
                rows.append({'id': item['Id'], 'rate': d.get('rate', 0),
                             **({'mvp': True} if kind == 'mvp_drops' else {}),
                             **({'rare': True} if d.get('rate', 0) < RARE_RATE or item.get('Type') == 'Card' else {})})
        monsters[mid] = {'name': hunted[mid]['name'], 'drops': rows}
    table = {}
    for iid, item in sorted(used.items(), key=lambda kv: int(kv[0])):
        buy, sell = prices(item)
        table[iid] = {'name': item.get('Name', item['AegisName']), 'type': item.get('Type', 'Etc'),
                      'buy': buy, 'sell': sell, 'weight': int(item.get('Weight', 0)) / 10}
    return {'version': 1,
            'source': {'rathena_commit': commit(RATHENA), 'mob_db': MOB_DB, 'item_db': list(ITEM_DBS),
                       'monsters': 'config/p5-monsters.json'},
            'note': 'Generated by scripts/build_p5_loot.py; do not edit by hand. rate: 1/10000 at 1x.',
            'monsters': monsters, 'items': table}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', default=str(ROOT/'config/p5-loot.json'))
    args = parser.parse_args()
    doc = build()
    Path(args.out).write_text(json.dumps(doc, indent=1, ensure_ascii=False) + '\n', encoding='utf-8')
    print(f"{len(doc['monsters'])} monsters, {len(doc['items'])} items -> {args.out}")


if __name__ == '__main__':
    main()
